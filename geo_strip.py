"""geo_strip.py — удаление гео-токенов (города/регионы РФ) из позитивных ключей слепков.

Применяется при чтении пака (kontent_pack.read_keywords / gather): делает ключи
геонейтральными — слепок самарского директолога без изменений работает в Кемерово.

Механика:
  - Гео-токен убираем И из позитива, И из-под оператора (-/!/+/[/") — правило G8:
    гео-города чистим даже в минус-частях фразы. Для токена под оператором снимаем
    операторную обёртку и сверяем ядро (сам топоним) по словарю; гео → выкидываем
    ВЕСЬ токен (оператор+город). НЕ-гео минус (-бесплатно, -фото) и обрезок-минус,
    не совпавший с полной формой (-самар), остаются как есть.
  - Многословные топонимы («краснодарский край», «нижний новгород») обрабатываются
    до однословных, чтобы не оставлять висячих «в/крае».
  - После зачистки пустые строки отбрасываются, дедуп (caseless) выполняется вызывающей стороной
    (dedup — внутри одного файла ct, см. normalize_geo_lines).

Покрытие (сознательно неполное, честно):
  ~40 городов-миллионников и региональных центров + их склоняемые формы.
  НЕ включены заведомо двусмысленные: Орёл (птица/город), Владимир (имя/город),
  «нижний» в одиночку (прилагательное), Россия/России (страна, не город).
  Охват расширяется: добавить формы в _GEO или _MULTI_GEO.
"""
from __future__ import annotations

# Операторные префиксы Яндекс.Директа.  Токен под оператором сверяем по ядру.
_OP_PREFIX_CHARS: str = "!+-[\""
_OP_PREFIXES: frozenset[str] = frozenset(_OP_PREFIX_CHARS)
# Хвостовые обёртки, которые снимаем с ядра токена: [краснодарский край] / "самара".
_OP_SUFFIX_CHARS: str = "]\""


def _geo_core(low_tok: str) -> str:
    """Ядро токена без операторной обёртки для сверки с гео-словарём.

    Позитивный токен возвращается как есть.  Под оператором — снимаем ведущие
    операторные префиксы (-/!/+/[/") и хвостовые ]/" : «-екатеринбург»→«екатеринбург»,
    «[краснодарский»→«краснодарский», «край]»→«край».  Токен из одних операторов → ''.
    """
    if not low_tok:
        return ""
    if low_tok[0] in _OP_PREFIXES:
        return low_tok.lstrip(_OP_PREFIX_CHARS).rstrip(_OP_SUFFIX_CHARS)
    return low_tok

