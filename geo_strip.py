_SINGLE_TOKEN_GEO: frozenset[str] = _GEO | frozenset(p for p in _MULTI_GEO if " " not in p)

# ── Предлоги-связки гео (позитивные, без оператор-префикса) ───────────────────
# Убираются ТОЛЬКО когда непосредственно предшествовали удалённому гео-токену
# (позиция «<предлог> <город>») либо остались висеть в хвосте фразы.
# «в кредит» / «в наличии» НЕ трогаются: там после предлога идёт НЕ-гео слово.
