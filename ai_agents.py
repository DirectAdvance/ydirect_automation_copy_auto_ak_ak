def _bad_for_new(s: str) -> bool:
    """True, если строка содержит лексику «с пробегом / б/у» — неуместную на сайте про НОВЫЕ авто."""
    return bool(_USED_BAN_RE.search(s or ""))


def strip_used_words(s: str) -> str:
    """Убирает «с пробегом / б/у / подержанные» из строки (для сайтов про НОВЫЕ авто).
    «на автомобили с пробегом» → «на автомобили». Чистит сдвоенные пробелы/предлоги-хвосты."""
    s = _USED_BAN_RE.sub("", s or "")
    s = re.sub(r"\s+([.,;:])", r"\1", s)
    s = re.sub(r"\s{2,}", " ", s).strip()
    return _strip_trailing_danglers(s) if s else s



def alien_signature(agent_key: str, s: str) -> bool:
    """True, если строка содержит УНИКАЛЬНУЮ сигнатуру ДРУГОГО слепка (кросс-контаминация).
    Используется серверным фильтром генерации контента — отбрасывает строки с чужим голосом."""
    rx = ALIEN_SIGNATURE_RE.get((agent_key or "").strip().lower())
    return bool(rx and rx.search(s or ""))


