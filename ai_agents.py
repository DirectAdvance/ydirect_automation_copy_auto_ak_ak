        # D11 (2026-07-09) — стиль формулировок в ТЕКСТАХ (слово «автокредит» в текстах НЕ используем —
        # оно блокируется фильтром; пиши «в кредит»):
        + "✅ ФОРМУЛИРОВКА КРЕДИТА: не пиши канцелярское «кредит на авто» — формулируй естественно: "
        + "«в кредит», «в кредит от 9 000 ₽/мес», «покупка в кредит», «оформить в кредит».\n"
        + "✅ ГОСПРОГРАММА И ВЫГОДА — В ПРОЦЕНТАХ («господдержка 20%», «скидка до 45%»), а не суммой "
