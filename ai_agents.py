def build_density_upgrade_messages(short_titles: list, all_titles: list,
                                    agent: dict, ctx: dict,
                                    item: dict | None = None,
                                    brand: str = "") -> list[dict]:
    """Промпт-расширитель: принимает список коротких заголовков (48-52 симв) и просит LLM
    расширить каждый до TITLE_DENSE_MIN–TITLE_MAX симв, добавляя конкретную деталь.

    Порядок возврата совпадает с порядком short_titles.
    → JSON: {\"titles\": [\"расширенный1\", ...]} — список той же длины.
    Вызывается из create_content.run_gen_campaign_content (density-upgrade pass)."""
    site_type = (ctx.get("site_type") or "").strip()
    city = (ctx.get("city") or "").strip()
    item = item or {}
    n = len(short_titles)
    short_block = "\n".join(
        f'  {i + 1}. «{t}» ({len(t)} симв — нужно {TITLE_DENSE_MIN}–{TITLE_MAX})'
        for i, t in enumerate(short_titles)
    )
    # уже принятые (не-короткие) — LLM не должен их копировать
    already_dense = [t for t in (all_titles or []) if t not in short_titles]
    avoid_block = ("; ".join(f"«{t}»" for t in already_dense[:5])
                   if already_dense else "нет")
    brand_rule = (
        f"Бренд «{brand}» — первое слово каждого заголовка (brand-first, не менять).\n"
        if brand else ""
    )
    sys = (
        f"Задача: расширь каждый из {n} коротких заголовков до {TITLE_DENSE_MIN}–{TITLE_MAX} символов.\n"
        "Правило расширения: добавь ОДНУ конкретную деталь — «от», число банков, ставку, срок, "
        "КАСКО в подарок, процент скидки, «Взнос 0 ₽» или «за 1 час». "
        "Смысл и кредитный угол сохрани.\n"
        f"{brand_rule}"
        "Кредитный угол ОБЯЗАТЕЛЕН в каждом заголовке: кредит, платёж, взнос, одобрение, автокредит.\n"
        f"В каждом заголовке нужна цифра (платёж ₽/мес, %, банки, срок).\n"
        f"ЖЁСТКО: ≥{TITLE_DENSE_MIN} и ≤{TITLE_MAX} символов — за пределами будет отброшено.\n"
        "⛔ НЕЛЬЗЯ копировать уже принятые заголовки: " + avoid_block + ".\n"
        "⛔ ЗАПРЕЩЕНО тире «—»/«–» и дефис «-» как разделитель фраз.\n"
        f"Сайт: {site_type}. Город: {city}.\n"
        f"Верни JSON РОВНО с {n} строками (по порядку заголовков из списка):\n"
        '{"titles": ["расширенный1", "расширенный2", ...]}\n\n'
        "Заголовки для расширения:\n"
        + short_block
    )
    return [
        {"role": "system", "content": sys},
        {"role": "user",
         "content": f"Расширь {n} заголовков до {TITLE_DENSE_MIN}–{TITLE_MAX} символов. Только JSON."},
    ]


