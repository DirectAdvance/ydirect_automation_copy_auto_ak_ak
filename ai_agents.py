def next_promo_type(avoid_types: list | None, default_type: str = "DISCOUNT") -> str:
    """Следующий тип акции для регенерации: первый из ротации, ещё НЕ показанный.
    Если показаны все — берём первый, отличный от последнего показанного (чтобы крутилось)."""
    used = [str(t).upper() for t in (avoid_types or [])]
    for t in PROMO_TYPE_ROTATION:
        if t not in used:
            return t
    last = used[-1] if used else default_type
    for t in PROMO_TYPE_ROTATION:
        if t != last:
            return t
    return PROMO_TYPE_ROTATION[0]

