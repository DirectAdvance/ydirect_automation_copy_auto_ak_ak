def _sitelink_desc_key(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "").lower()).strip()


def _dup_key(s: str) -> str:
    """Нормализованный ключ для отлова заголовков-БЛИЗНЕЦОВ: «Распродажа б/у авто. Выгода до 45%»
    и «Распродаём б/у авто. Скидка до 45%» → один ключ (распродажа/распродаём и скидка/выгода
    схлопываются), чтобы оба не прошли в выдачу."""
    k = (s or "").lower()
    k = re.sub(r"распрода\w+", "распродажа", k)
    k = re.sub(r"скидк\w*|выгод\w*", "выгода", k)        # скидка ≈ выгода для дедупа
    k = re.sub(r"обмен\w*|обменя\w*", "обмен", k)
    k = re.sub(r"б\s*/?\s*у|с\s+пробегом", "бу", k)       # б/у ≈ с пробегом
    k = re.sub(r"[^\wа-яё%]+", " ", k)
    return re.sub(r"\s+", " ", k).strip()


def _dedup_titles(seq: list[str]) -> list[str]:
    """Дедуп заголовков по нормализованному ключу (схлопывает близнецы-перефразировки)."""
    seen, out = set(), []
    for x in seq:
        if not x:
            continue
        k = _dup_key(x)
        if k not in seen:
            seen.add(k)
            out.append(x)
    return out


def _title_utp_bucket(s: str) -> str:
    """Грубая корзина УТП заголовка, чтобы не собирать 5 вариаций одной «скидки».
    Нужна и для раннего фильтра M3, и для финальной добивки из корпуса."""
    x = (s or "").lower()
    if not x:
        return ""
    if re.search(r"(трейд-?ин|обмен)", x):
        return "tradein"
    if re.search(r"(каско|подар|шин|комплект)", x):
        return "gift"
    if re.search(r"(плат[её]ж|/мес)", x):
        return "payment"
    if re.search(r"(взнос)", x):
        return "downpay"
    if re.search(r"(господдерж|госпрограм|утильсбор|одобр)", x):
        return "support"
    if re.search(r"(распрод|склад|стоянк|завоз|в наличии|готов\w*\s+к\s+выдаче)", x):
        return "sale"
    if "%" in x and re.search(r"(скидк|выгод|акци)", x):
        return "discount_pct"
    if re.search(r"(скидк|выгод|акци)", x) and re.search(r"\d[\d\s]*\s*(₽|руб)", x):
        return "discount_rub"
    if re.search(r"(скидк|выгод|акци)", x):
        return "discount_generic"
    if re.search(r"(кредит|автокредит)", x):
        return "credit"
    if re.search(r"\d[\d\s]*\s*(₽|руб)", x):
        return "price_rub"
    return "other"


def _sitelink_utp_bucket(s: str) -> str:
    """Корзина УТП для быстрых ссылок. Нужна строже, чем для заголовков РК:
    не хотим 8 ссылок подряд только про скидку/выдачу."""
    x = (s or "").lower()
    if not x:
        return ""
    # Подарочные УТП проверяем раньше кредита: «КАСКО ... при покупке в кредит»
    # должно считаться подарком/страховкой, а не ещё одной кредитной ссылкой.
    if re.search(r"(каско|подар|шин|комплект)", x):
        return "gift"
    if re.search(r"(кредит|автокредит|плат[её]ж|/мес|взнос|одобр|документ)", x):
        return "credit"
    if re.search(r"(трейд-?ин|обмен)", x):
        return "tradein"
    if re.search(r"(господдерж|госпрограм|утильсбор)", x):
        return "support"
    if re.search(r"(тест-?драйв)", x):
        return "testdrive"
    if re.search(r"(скидк|выгод|акци|%)", x):
        return "discount"
    if re.search(r"(в наличии|готов\w*\s+к\s+выдаче|наличи\w+)", x):
        return "availability"
    if re.search(r"(распрод|склад|стоянк|завоз)", x):
        return "sale"
    return "other"


def diversify_sitelink_utp(seq: list[dict], limit: int = 0) -> list[dict]:
    """Сначала берём быстрые ссылки с разными офферами, затем остаток."""
    out: list[dict] = []
    rest: list[dict] = []
    seen_bucket: set[str] = set()
    for s in seq:
        if not isinstance(s, dict):
            continue
        bucket = _sitelink_utp_bucket((s.get("title") or "") + " " + (s.get("description") or ""))
        if bucket and bucket not in seen_bucket:
            seen_bucket.add(bucket)
            out.append(s)
        else:
            rest.append(s)
    out.extend(rest)
    return out[:limit] if limit > 0 else out


_SITELINK_BARE_PCT_RE = re.compile(r"^\s*(\d{1,2})\s*%")
_SITELINK_NEG_PCT_RE = re.compile(r"(?i)(скидк\w*|выгод\w*|акци\w*)\s*(?:до\s*)?-\s*(\d{1,2})\s*%")
_SITELINK_REPEAT_SALE_RE = re.compile(r"(?i)\bготов\w*\s+к\s+выдаче\b")
_SITELINK_WEAK_DESC_RE = re.compile(
    r"(?i)(тест-?драйв\s+с\s+готов\w*\s+авто|готов\w*\s+авто\s+по\s+спеццен|"
    r"спешите,\s*акция|действует\s+ограниченное\s+время|готов\w*\s+к\s+выдаче)")
_SITELINK_BUCKET_LIMITS = {
    "discount_sale": 1,
    "availability": 1,
    "credit": 2,
    "tradein": 1,
    "gift": 2,
    "support": 1,
    "testdrive": 1,
    "other": 1,
}


def _sitelink_bucket_limits(site_type: str = "") -> dict[str, int]:
    """Лимиты повторов УТП в быстрых ссылках.
    Для Квиза ещё жёстче: это сценарий расчёта/подбора, а не шоурум."""
    limits = dict(_SITELINK_BUCKET_LIMITS)
    if (site_type or "").strip() == "Квиз":
        limits["discount_sale"] = 0
        limits["availability"] = 0
        limits["other"] = 2
    if (site_type or "").strip() in {"С пробегом", "Мульти + БУ"}:
        limits["other"] = 2
    return limits


def _normalize_sitelink_offer(s: str) -> str:
    """Чистит типовые артефакты быстрых ссылок:
    - «-35% на Geely» / «35% на Geely» -> «Скидка до 35% на Geely»
    - «Скидка до -30%» -> «Скидка до 30%»
    """
    x = str(s or "").strip()
    x = _SITELINK_NEG_PCT_RE.sub(lambda m: f"{m.group(1)} до {m.group(2)}%", x)
    m = _SITELINK_BARE_PCT_RE.match(x)
    if m:
        x = f"Скидка до {m.group(1)}%" + x[m.end():]
    x = re.sub(r"(?i)\bскидка\s+до\s+до\s+", "Скидка до ", x)
    x = re.sub(r"(?i)\bскидка\s+до\s+(\d{1,2})%\s+скидка\b", r"Скидка до \1%", x)
    x = re.sub(r"(?i)\bскидка\s+до\s+(\d{1,2})%\s+на\s+скидка\b", r"Скидка до \1%", x)
    x = re.sub(r"(?i)\bскидка\s+до\s+(\d{1,2})%\s+выгода\b", r"Скидка до \1%", x)
    x = re.sub(r"(?i)\bкрупная\s+выгода\s+до\s+(\d{1,2})%\s*₽", r"Выгода до \1% по кредиту", x)
    x = re.sub(r"(?i)\bавтокредит\s+до\s+(\d{1,2})%\s+выгод[аы]\b", r"Выгода до \1% по автокредиту", x)
    x = re.sub(r"(?i)\bвыгода\s+до\s+(\d{1,2})%\s*₽", r"Выгода до \1% по кредиту", x)
    x = re.sub(r"(?i)\b(скидка|выгода)\s+до\s+(\d{2,3})\s*₽",
               lambda m: f"{m.group(1).capitalize()} до {int(m.group(2)) * 1000:,}".replace(",", " ") + " ₽",
               x)
    x = re.sub(r"\s+", " ", x).strip(" ,.;:—–-")
    return x


def _bad_sitelink_phrase(s: str) -> bool:
    """Грубый стоп-лист плохих быстрых ссылок."""
    x = (s or "").lower()
    if not x:
        return True
    if _SITELINK_VEHICLE_RE.search(x):
        return True
    if has_forbidden_claim(x):
        return True
    if re.search(r"(?i)(\bосаго\b|комисс\w*\s+по\s+кредит|скрыт\w*\s+комисс|"
                 r"тест-?драйв\s+готов\w*\s+авто|готов\w*\s+авто|"
                 r"\b(?:скидк\w*|выгод\w*)\s+до\s+\d{2,3}\s*₽|"
                 r"\b\w+\s+до\s+\d{1,2}%\s*₽|"
                 r"автокредит\s+до\s+\d{1,2}%\s+выгод|"
                 r"\bот\s*0\s*(?:₽|руб\.?|рублей)?\s*(?:/мес|в\s+месяц)|"
                 r"(?:госпрограмм|господдержк)\w*.*в\s+подарок|"
                 r"в\s+подарок.*(?:госпрограмм|господдержк)\w*)", x):
        return True
    if _SITELINK_BARE_PCT_RE.match(x):
        return True
    if re.search(r"(?i)\b\d{1,2}\s*%\s+на\b", x) and "скид" not in x and "выгод" not in x:
        return True
    if re.search(r"(?i)\b(проверенн\w*\s+автосалон|выдача\s+автомобиля\s+сразу)\b", x):
        return True
    if re.search(r"(?i)\bскидка\s+до\s+\d{1,2}%\s+скидка\b", x):
        return True
    if _SITELINK_WEAK_DESC_RE.search(x):
        return True
    return False


def _can_take_sitelink(bucket_counts: dict[str, int], ti: str, de: str, site_type: str = "") -> bool:
    bucket = _sitelink_utp_bucket((ti or "") + " " + (de or ""))
    key = "discount_sale" if bucket in {"discount", "sale"} else (bucket or "other")
    lim = _sitelink_bucket_limits(site_type).get(key, 1)
    return bucket_counts.get(key, 0) < lim


def _take_sitelink(bucket_counts: dict[str, int], ti: str, de: str) -> None:
    bucket = _sitelink_utp_bucket((ti or "") + " " + (de or ""))
    key = "discount_sale" if bucket in {"discount", "sale"} else (bucket or "other")
    bucket_counts[key] = bucket_counts.get(key, 0) + 1


def _sitelink_norm_key(s: str) -> str:
    x = _normalize_sitelink_offer(str(s or "").lower())
    x = re.sub(r"распрода\w+", "распродажа", x)
    x = re.sub(r"скидк\w*|выгод\w*", "скидка", x)
    x = re.sub(r"\d[\d\s]*\s*₽", "#₽", x)
    x = re.sub(r"\d{1,2}\s*%", "#%", x)
    x = re.sub(r"[^\wа-яё#%₽]+", " ", x)
    return re.sub(r"\s+", " ", x).strip()


def _sitelink_semantic_key(ti: str, de: str) -> str:
    """Смысловой ключ быстрой ссылки.
    Нужен для схлопывания пар discount/sale, когда они по сути говорят об одной скидке
    через одинаковое описание."""
    blob = _normalize_sitelink_offer(f"{ti} {de}")
    if re.search(r"(?i)\bкаско\b", blob):
        return "gift_kasko"
    if re.search(r"(?i)\b(шин|резин|комплект\s+шин)\w*\b", blob):
        return "gift_tires"
    if re.search(r"(?i)\bтрейд-?ин|обмен\b", blob):
        return "tradein"
    title_bucket = _sitelink_utp_bucket(ti)
    group = "discount_sale" if title_bucket in {"discount", "sale"} else title_bucket or "other"
    desc_key = _sitelink_norm_key(de)
    title_key = _sitelink_norm_key(ti)
    pct = None
    m = re.search(r"(\d{1,2})\s*%", blob)
    if m:
        pct = m.group(1)
    pay = None
    for pm in _UTP_PAY_RE.finditer(f"{ti} {de}"):
        if _utp_pay_ok(pm):
            pay = re.sub(r"\D", "", pm.group(3))
            break
    if group == "credit" and pay:
        return f"credit_pay|{pay}"
    core = desc_key or title_key
    return f"{group}|{pct or ''}|{core}"


def _dedup_sitelinks(seq: list[dict], site_type: str = "", limit: int = 0) -> list[dict]:
    # Фаза 1: обычный дедуп (заголовок/описание/семантика/корзина).
    cand: list[tuple[str, str, str]] = []   # (title, description, primary_number)
    seen_title: set[str] = set()
    seen_desc: set[str] = set()
    seen_semantic: set[str] = set()
    bucket_counts: dict[str, int] = {}
    for s in seq:
        if not isinstance(s, dict):
            continue
        ti = str(s.get("title") or "").strip()
        de = str(s.get("description") or "").strip()
        if (not ti or len(ti) < SITELINK_TITLE_TARGET_MIN or len(de) < SITELINK_DESC_TARGET_MIN
                or _bad_sitelink_phrase(ti) or _bad_sitelink_phrase(de)):
            continue
        tk = _sitelink_norm_key(ti)
        dk = _sitelink_norm_key(de)
        sk = _sitelink_semantic_key(ti, de)
        if tk in seen_title or (dk and dk in seen_desc) or sk in seen_semantic:
            continue
        if not _can_take_sitelink(bucket_counts, ti, de, site_type):
            continue
        seen_title.add(tk)
        if dk:
            seen_desc.add(dk)
        seen_semantic.add(sk)
        _take_sitelink(bucket_counts, ti, de)
        _nums = re.findall(r"\d+", f"{ti} {de}")
        cand.append((ti, de, _nums[0] if _nums else ""))
    # Фаза 2: разнообразие ЦИФР — не более 2 сайтлинков с одной и той же цифрой (баг: 4×«30»).
    # Сначала с капом, затем добор остатком (чтобы не уйти ниже лимита, если все на одну цифру).
    out: list[dict] = []
    num_counts: dict[str, int] = {}
    for ti, de, num in cand:
        if limit > 0 and len(out) >= limit:
            break
        if num and num_counts.get(num, 0) >= 2:
            continue
        if num:
            num_counts[num] = num_counts.get(num, 0) + 1
        out.append({"title": ti, "description": de})
    if limit <= 0 or len(out) < limit:
        _chosen = {(o["title"], o["description"]) for o in out}
        for ti, de, _num in cand:
            if limit > 0 and len(out) >= limit:
                break
            if (ti, de) in _chosen:
                continue
            out.append({"title": ti, "description": de})
    return out


def diversify_title_utp(seq: list[str], limit: int = 0) -> list[str]:
    """Сначала берём заголовки с разными корзинами УТП, затем остаток.
    Это не даёт набору схлопнуться в пять скидок подряд."""
    out: list[str] = []
    seen_bucket: set[str] = set()
    rest: list[str] = []
    for x in seq:
        if not x:
            continue
        bucket = _title_utp_bucket(x)
        if bucket and bucket not in seen_bucket:
            seen_bucket.add(bucket)
            out.append(x)
        else:
            rest.append(x)
    out.extend(rest)
    return out[:limit] if limit > 0 else out


def validate_campaign(d: dict, agent: dict, site_type: str = "") -> tuple[dict, list[str]]:
    """Валидирует/чистит контент РК от модели → ({titles, texts, sitelinks}, warns).
    Обрезает по лимитам, чистит запрещённые символы быстрых ссылок, добивает
    недостающее из банка полных примеров (по типу сайта), затем из корпуса агента."""
    ads = agent.get("ads", {})
    bu_mode = (site_type or "").strip() == "С пробегом"
    # Добивка ТОЛЬКО из корпуса агента (банк в контент НЕ идёт — он лишь образец для промпта).
    pool_titles = list(ads.get("titles", []))
    pool_texts = list(ads.get("texts", []))
    pool_sl = sitelink_bank_for(site_type, "") + list(ads.get("sitelinks", []))
    # Для «С пробегом» выкидываем «новоавтомобильные» формулировки + нереалистичный % скидки.
    if bu_mode:
        pool_titles = [t for t in pool_titles if not _bad_for_bu(t) and not _bad_pct_bu(t)]
        pool_texts = [t for t in pool_texts if not _bad_for_bu(t) and not _bad_pct_bu(t)]
        pool_sl = [(t, dd) for t, dd in pool_sl
                   if not _bad_for_bu(t) and not _bad_for_bu(dd) and not _bad_pct_bu(t) and not _bad_pct_bu(dd)]
    warns: list[str] = []

    def _keep(t: str) -> bool:
        if not (t or "").strip():
            return False
        if has_forbidden_claim(t):
            return False
        if has_cashback(t) or has_installment(t):          # глобальный запрет кешбэка/рассрочки
            return False
        return not (bu_mode and (_bad_for_bu(t) or _bad_pct_bu(t)))

    raw_titles: list[str] = []
    for t in (d.get("titles") or []):
        if isinstance(t, dict):
            cand = str(t.get("title1") or t.get("title") or t.get("headline") or t.get("text") or "").strip()
        else:
            cand = str(t or "").strip()
        if cand and _keep(cand):
            raw_titles.append(cand)
    titles = _dedup_titles([_clean_line(t, TITLE_MAX) for t in raw_titles])
    titles = titles[:TITLES_N]
    raw_texts: list[str] = []
    for t in (d.get("texts") or []):
        if isinstance(t, dict):
            cand = str(t.get("text") or t.get("body") or t.get("description") or t.get("copy") or "").strip()
        else:
            cand = str(t or "").strip()
        if cand and _keep(cand):
            raw_texts.append(cand)
    texts = _dedup_texts([_clean_line(t, TEXT_MAX) for t in raw_texts])
    texts = texts[:TEXTS_N]

    raw_sl = d.get("sitelinks") or []
    sitelinks: list[dict] = []
    seen_sl: set = set()       # дедуп по заголовку
    seen_desc: set = set()     # дедуп по полному описанию
    sl_bucket_counts: dict[str, int] = {}

    for s in raw_sl:
        if isinstance(s, dict):
            ti = _clean_line(s.get("title") or s.get("Title") or "", SITELINK_TITLE_MAX, sitelink=True)
            de = _clean_line(s.get("description") or s.get("Description") or "", SITELINK_DESC_MAX, sitelink=True)
        else:
            ti, de = _clean_line(str(s), SITELINK_TITLE_MAX, sitelink=True), ""
        if has_cashback(ti) or has_cashback(de) or has_installment(ti) or has_installment(de):
            continue   # глобальный запрет кешбэка/рассрочки
        if bu_mode and (_bad_for_bu(ti) or _bad_for_bu(de)):
            continue   # на б/у-сайте выкидываем новоавтомобильные ссылки
        if _bad_sitelink_phrase(ti) or _bad_sitelink_phrase(de):
            continue
        tk = _sitelink_title_key(ti)
        dk = _sitelink_desc_key(de)
        # Директ не принимает одинаковые title/description внутри одной кампании.
        if ti and tk not in seen_sl and (not dk or dk not in seen_desc) and _can_take_sitelink(sl_bucket_counts, ti, de, site_type):
            seen_sl.add(tk)
            if dk:
                seen_desc.add(dk)
            _take_sitelink(sl_bucket_counts, ti, de)
            sitelinks.append({"title": ti, "description": de})
    sitelinks = _dedup_sitelinks(diversify_sitelink_utp(sitelinks, SITELINKS_N), site_type, SITELINKS_N)

    # Добивка из корпуса, если модель вернула недостаточно.
    def _pad_lines(cur: list[str], pool: list[str], n: int, maxlen: int):
        padded = False
        for ex in pool:
            if len(cur) >= n:
                break
            c = _clean_line(ex, maxlen)
            if c and c.lower() not in {x.lower() for x in cur}:
                cur.append(c)
                padded = True
        return padded

    if _pad_lines(titles, pool_titles, TITLES_N, TITLE_MAX):
        warns.append("заголовки дополнены из корпуса агента")
    if _pad_lines(texts, pool_texts, TEXTS_N, TEXT_MAX):
        warns.append("тексты дополнены из корпуса агента")
    if len(sitelinks) < SITELINKS_N:
        before = len(sitelinks)
        for ti, de in pool_sl:
            if len(sitelinks) >= SITELINKS_N:
                break
            ct = _clean_line(ti, SITELINK_TITLE_MAX, sitelink=True)
            cd = _clean_line(de, SITELINK_DESC_MAX, sitelink=True)
            if _bad_sitelink_phrase(ct) or _bad_sitelink_phrase(cd):
                continue
            tk = _sitelink_title_key(ct)
            dk = _sitelink_desc_key(cd)
            if ct and tk not in seen_sl and (not dk or dk not in seen_desc) and _can_take_sitelink(sl_bucket_counts, ct, cd, site_type):
                seen_sl.add(tk)
                if dk:
                    seen_desc.add(dk)
                _take_sitelink(sl_bucket_counts, ct, cd)
                sitelinks.append({"title": ct, "description": cd})
        if len(sitelinks) > before:
            warns.append("быстрые ссылки дополнены из корпуса стиля")
    sitelinks = _dedup_sitelinks(diversify_sitelink_utp(sitelinks, SITELINKS_N), site_type, SITELINKS_N)

    # Гарантируем минимум для движка (хотя бы 1 заголовок и 1 текст).
    if not titles:
        titles = [_clean_line(t, TITLE_MAX) for t in (pool_titles or ["Автомобили в кредит"])[:1]]
    if not texts:
        texts = [_clean_line(t, TEXT_MAX) for t in (pool_texts or ["Выгодные условия. Звоните!"])[:1]]

    # Title2: извлекаем из ответа модели, обрезаем до TITLE2_MAX.
    title2_raw = strip_installment((d.get("title2") or "").strip().strip('"'))
    if has_cashback(title2_raw):
        title2_raw = ""
        warns.append("title2 содержал кешбэк — удалён")
    if has_installment(title2_raw):
        title2_raw = ""
        warns.append("title2 содержал рассрочку — удалён")
    title2 = title2_raw[:TITLE2_MAX] if title2_raw else ""

    # ГАРД единых чисел УТП: один % скидки/выгоды и один платёж кредита на весь набор.
    titles, texts, title2, sitelinks, _u = unify_utp_numbers(titles, texts, title2, sitelinks)
    texts = _dedup_texts(texts)
    if _u:
        warns.append("числа УТП приведены к единому значению (% скидки / платёж кредита)")
    sitelinks = _dedup_sitelinks(sitelinks, site_type, SITELINKS_N)

    clean = {"titles": titles[:TITLES_N], "texts": texts[:TEXTS_N], "sitelinks": sitelinks[:SITELINKS_N],
             "title2": title2}
    return clean, warns


def assemble_campaign(titles: list, texts: list, sitelinks: list, agent: dict,
                      site_type: str = "", brand: str = "") -> tuple[dict, list[str]]:
    """Финальная сборка с ГАРАНТИЕЙ длины: оставляет заголовки ≥TITLE_TARGET_MIN и тексты
    ≥TEXT_TARGET_MIN, недостающее добивает ПОЛНЫМИ примерами из банка/корпуса. → (content, warns).
    Используется после цикла перегенерации (короткие строки уже отброшены в эндпоинте).
    Эталонный банк (EXAMPLE_BANK) в контент НЕ добивается — только корпус самого слепка."""
    st = (site_type or "").strip()
    bu = is_bu_site_type(st)
    new_only = st in NEW_ONLY_SITE_TYPES
    ads = agent.get("ads", {})
    warns: list[str] = []
    brand_word = (brand.split()[0].strip() if brand else "")
    brand_re = (re.compile(r"(?i)\b" + re.escape(brand_word) + r"\b") if brand_word else None)
    title_credit_re = re.compile(r"(?i)(кредит|автокредит|плат[её]ж|/мес|взнос|одобр)")
    title_sale_ok_re = re.compile(r"(?i)(распрод|склад|стоянк|завоз)")
    title_utp_re = re.compile(
        r"(?i)(\d|кредит|плат[её]ж|скидк|выгод|распрод|трейд-?ин|каско|подар|в наличии|господдерж|госпрограм|"
        r"одобр|акци|тест-?драйв|шин|взнос)")
    text_utp_re = re.compile(
        r"(?i)(\d|кредит|плат[её]ж|скидк|выгод|трейд-?ин|каско|подар|в наличии|господдерж|госпрограм|"
        r"одобр|акци|тест-?драйв|шин|взнос|документ|комплект|ключи)")
    cta_re = re.compile(r"(?i)(звонит|остав(?:ь|ьте)\s+заявк|оставьте\s+контакт|запишит|приезжайт|узнайте|получите)")

    def _mismatch(c: str) -> bool:
        # строка не подходит: кешбэк (глобальный запрет); б/у-сайт → новоавтомобильное/нереалистичный %;
        # новый сайт → «с пробегом/б/у»
        return (has_forbidden_claim(c) or has_cashback(c) or has_installment(c) or (bu and (_bad_for_bu(c) or _bad_pct_bu(c)))
                or (new_only and _bad_for_new(c))
                or bool(re.search(r"(?i)\bбез\s+документ", c or "")))

    def _brand_ok(c: str) -> bool:
        return (not brand_re) or bool(brand_re.search(c or ""))

    def _title_ok(c: str) -> bool:
        return (_brand_ok(c) and bool(title_utp_re.search(c or ""))
                and bool(title_credit_re.search(c or "") or title_sale_ok_re.search(c or "")))

    def _text_ok(c: str) -> bool:
        return _brand_ok(c) and bool(text_utp_re.search(c or "")) and bool(cta_re.search(c or ""))

    def _sitelink_ok(ti: str, de: str) -> bool:
        if _bad_sitelink_phrase(ti) or _bad_sitelink_phrase(de):
            return False
        return not (_SITELINK_VEHICLE_RE.search(ti or "") or _SITELINK_VEHICLE_RE.search(de or ""))

    def _pad(cur: list, pools: list, n: int, minlen: int, maxlen: int):
        cleaned_cur = []
        for x in cur or []:
            c = _clean_line(x, maxlen)
            if c:
                cleaned_cur.append(c)
        if maxlen == TITLE_MAX:
            out = [x for x in cleaned_cur if len(x) >= minlen and not _mismatch(x) and _title_ok(x)]
        else:
            out = [x for x in cleaned_cur if len(x) >= minlen and not _mismatch(x) and _text_ok(x)]
        seen = {x.lower() for x in out}
        padded = False

        def _take(pool: list, floor: int):
            nonlocal padded
            for ex in pool:
                if len(out) >= n:
                    break
                c = _clean_line(ex, maxlen)
                if _mismatch(c):
                    continue
                if maxlen == TITLE_MAX and not _title_ok(c):
                    continue
                if maxlen != TITLE_MAX and not _text_ok(c):
                    continue
                if len(c) >= floor and c.lower() not in seen:
                    seen.add(c.lower()); out.append(c); padded = True

        for pool in pools:               # сначала корпус агента (его стиль), потом банк по типу сайта
            _take(pool, minlen)
        if len(out) < n:                 # ≥minlen не хватило
            if maxlen == TITLE_MAX:      # заголовки: не снижаем порог до 40; лучше повторить одобренный чем взять короткий
                _approved = list(out)
                _idx = 0
                while _approved and len(out) < n:
                    out.append(_approved[_idx % len(_approved)])
                    _idx += 1
                    padded = True
            else:                        # тексты: добираем чуть короче, не оставляя пустой слот
                for pool in pools:
                    _take(pool, max(40, minlen - 14))
        if maxlen == TITLE_MAX:
            out = diversify_title_utp(out, n)
        return out[:n], padded

    # Добивка ТОЛЬКО из корпуса самого слепка (его стиль). Эталонный банк сюда НЕ идёт —
    # он лишь ориентир полноты/длины в промпте, его фразы в контент не подмешиваются.
    titles = diversify_title_utp(_dedup_titles(titles), TITLES_N)   # сначала разные УТП, потом добивка
    titles, p1 = _pad(titles, [ads.get("titles", [])], TITLES_N, TITLE_TARGET_MIN, TITLE_MAX)
    texts, p2 = _pad(texts, [ads.get("texts", [])], TEXTS_N, TEXT_TARGET_MIN, TEXT_MAX)
    if p1:
        warns.append("заголовки дополнены из корпуса слепка")
    if p2:
        warns.append("тексты дополнены из корпуса слепка")

    sl: list[dict] = []
    seen_sl: set = set()
    seen_desc: set = set()
    sl_bucket_counts: dict[str, int] = {}
    for s in sitelinks:
        if len(sl) >= SITELINKS_N:
            break
        ct = _clean_line((s or {}).get("title") or "", SITELINK_TITLE_MAX, sitelink=True)
        cd = _clean_line((s or {}).get("description") or "", SITELINK_DESC_MAX, sitelink=True)
        if _mismatch(ct) or _mismatch(cd) or not _sitelink_ok(ct, cd):
            continue
        tk = _sitelink_title_key(ct)
        dk = _sitelink_desc_key(cd)
        if ct and tk not in seen_sl and (not dk or dk not in seen_desc) and _can_take_sitelink(sl_bucket_counts, ct, cd, st):
            seen_sl.add(tk)
            if dk:
                seen_desc.add(dk)
            _take_sitelink(sl_bucket_counts, ct, cd)
            sl.append({"title": ct, "description": cd})
    for ti, de in sitelink_bank_for(st, brand) + list(ads.get("sitelinks", [])):
        if len(sl) >= SITELINKS_N:
            break
        ct = _clean_line(ti, SITELINK_TITLE_MAX, sitelink=True)
        cd = _clean_line(de, SITELINK_DESC_MAX, sitelink=True)
        if _mismatch(ct) or _mismatch(cd) or not _sitelink_ok(ct, cd):
            continue
        tk = _sitelink_title_key(ct)
        dk = _sitelink_desc_key(cd)
        if ct and tk not in seen_sl and (not dk or dk not in seen_desc) and _can_take_sitelink(sl_bucket_counts, ct, cd, st):
            seen_sl.add(tk)
            if dk:
                seen_desc.add(dk)
            _take_sitelink(sl_bucket_counts, ct, cd)
            sl.append({"title": ct, "description": cd})
    sl = _dedup_sitelinks(diversify_sitelink_utp(sl, SITELINKS_N), st, SITELINKS_N)

    if not titles:
        for ex in ads.get("titles", []):
            c = _clean_line(ex, TITLE_MAX)
            if not _mismatch(c) and _title_ok(c):
                titles = [c]
                break
    if not texts:
        for ex in ads.get("texts", []):
            c = _clean_line(ex, TEXT_MAX)
            if not _mismatch(c) and _text_ok(c):
                texts = [c]
                break
    # D7/D11 (2026-07-09): аварийные фолбэки уплотнены (короткий текст ~52 симв → плотный ≤81) и
    # приведены к стилю. Заголовки: «Автокредит» (в заголовках слово разрешено), brand-first сохранён.
    # Тексты: «автокредит» НЕЛЬЗЯ (блокируется _BAD_AD_TEXT_RE) → «в кредит»; добавлен CTA «Купить».
    if not titles:
        if brand_word:
            titles = [f"{brand_word} в кредит от 9 000 ₽/мес. Первый взнос 0 ₽"]
        else:
            titles = ["Автокредит от 9 000 ₽/мес. Первый взнос 0 ₽"]
    if not texts:
        if brand_word:
            texts = [f"{brand_word} в кредит от 9 000 ₽/мес. Первый взнос 0 ₽. Быстрое одобрение."]
        else:
            texts = ["Купить авто в кредит от 9 000 ₽/мес. Первый взнос 0 ₽. Одобрение за 30 минут."]

    # ГАРД единых чисел УТП ПОСЛЕ добивки из корпуса (корпус мог принести иной % / платёж).
    sl = _dedup_sitelinks(sl, st, SITELINKS_N)
    titles, texts, _t2, sl, _u = unify_utp_numbers(titles, texts, "", sl)
    texts = _dedup_texts(texts)
    if len(texts) < TEXTS_N:
        seen_text_keys = {_text_semantic_key(x) for x in texts}
        for ex in ads.get("texts", []):
            if len(texts) >= TEXTS_N:
                break
            c = _clean_line(utp_apply(ex, None, None), TEXT_MAX)
            k = _text_semantic_key(c)
            if c and k not in seen_text_keys and not _mismatch(c) and _text_ok(c):
                seen_text_keys.add(k)
                texts.append(c)
    if _u:
        warns.append("числа УТП приведены к единому значению (% скидки / платёж кредита)")

    return {"titles": titles, "texts": texts, "sitelinks": sl}, warns


def build_campaign_messages(agent: dict, ctx: dict, item: dict | None = None,
                            avoid: list | None = None, brand: str = "") -> list[dict]:
    """Промпт для генерации контента ОДНОЙ РК набора: заголовки/тексты/быстрые ссылки.
    ctx: {domain, city, site_type, salon}. item: {name, type, variant} — какая это РК
    (мастер/товарная, авто/ручная), чтобы контент чуть различался.
    brand — марка/модель из КОДЕРА кампании/группы (первый ct с 4 цифрами → ag_part1, напр.
    «Lada» или «Lada Granta»); если задан, контент пишется ИМЕННО про этот бренд. Строгий JSON."""
    ads = agent.get("ads", {})
    city = ctx.get("city") or ""
    site_type = (ctx.get("site_type") or "").strip()
    st_hint = SITE_TYPE_PROFILE.get(site_type, "")
    item = item or {}
    kind = "товарная (под фид)" if item.get("type") == "product" else "мастер-кампания"
    strat = "ручная стратегия" if str(item.get("variant", "")).endswith("manual") else "автостратегия"
    brand = (brand or "").strip()
    # Блок жёсткой привязки к бренду кодера (если он есть): каждая строка — про эту марку.
    brand_block = ""
    if brand:
        _bw = brand.split()[0]
        brand_block = (
            f"🎯 БРЕНД/МОДЕЛЬ КАМПАНИИ ПО КОДЕРУ: {brand}. Пиши заголовки, тексты и быстрые ссылки "
            f"ИМЕННО про {brand} — это марка кампании. Указывай «{brand}» (или конкретные модели {_bw}) "
            f"в КАЖДОМ заголовке и тексте, где уместно. НЕ упоминай другие марки автомобилей. "
            f"Если тип сайта монобренд/квиз — весь контент строго про {_bw}.\n"
            f"⛔ НЕ пиши общее число машин САЛОНА («6500+ авто», «более 6500», «500+ авто в наличии», "
            f"«огромный выбор авто») — это про весь автосалон, а для одной марки {_bw} неуместно и недостоверно. "
            f"Про наличие пиши по-брендовому: «{_bw} в наличии», «модельный ряд {_bw}», «{_bw} разных комплектаций».\n")

    # СТИЛЬ И ТЕКСТЫ — ВСЕГДА от АГЕНТА (его корпус). Банк в контент НЕ идёт — он лишь
    # отдельный образец ПОЛНОТЫ/УТП для ориентира по длине. На «С пробегом» из корпуса агента
    # выкидываем новоавтомобильные строки; если агент такой сайт не вёл — он АДАПТИРУЕТ свой тон.
    bu = is_bu_site_type(site_type)
    new_only = site_type in NEW_ONLY_SITE_TYPES
    a_titles = [t for t in (ads.get("titles") or [])
                if not (bu and _bad_for_bu(t)) and not (new_only and _bad_for_new(t))]
    a_texts = [t for t in (ads.get("texts") or [])
               if not (bu and _bad_for_bu(t)) and not (new_only and _bad_for_new(t))]
    a_sl = [(t, dd) for t, dd in (ads.get("sitelinks") or [])
            if not (bu and (_bad_for_bu(t) or _bad_for_bu(dd)))
            and not (new_only and (_bad_for_new(t) or _bad_for_new(dd)))]
    ex_titles = "\n   • ".join(a_titles[:6]) or "(нет — адаптируй свой фирменный тон под этот тип сайта)"
