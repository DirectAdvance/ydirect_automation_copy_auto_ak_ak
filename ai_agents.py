# ── ЕДИНЫЕ ЧИСЛА УТП по всему набору РК (баг Павлова: в заголовке «кредит от 6 900»,
#    а в тексте «9 600»; «скидка 57%» и «58%» в разных строках). Директологу нужно ОДНО
#    значение платежа и ОДИН % скидки/выгоды на весь набор (заголовки+тексты+title2+ссылки).
#    Канон = ПЕРВОЕ встреченное значение (заголовки обрабатываются раньше), остальные правим.
#    % берём СТРОГО в контексте скидк/выгод — «98% одобрения», «99% выдач» НЕ трогаем.
# Скидочный %: маркер (скидк/выгод ИЛИ ведущий «-»), затем число и «%». Ловит «скидка до 57%»,
# «выгода 57%», «до -58%», «-30%». «98% одобрения» — без маркера, НЕ ловится.
_UTP_PCT_RE = re.compile(r"(?i)(скидк\w*|выгод\w*|[-–])(\s*до\s*|\s*)(\d{1,2})(\s*%)")
# Платёж/кредит «… N ₽ [в месяц|/мес]»: только МЕЛКИЙ ежемесячный платёж (1 000–99 999 ₽),
# не путать с выгодой/ценой в сотни тысяч ₽. Маркер — кредит/платёж/рассрочка ИЛИ «в месяц»/«/мес».
_UTP_PAY_RE = re.compile(
    r"(?i)((?:авто)?кредит\w*|платёж\w*|платеж\w*|рассрочк\w*)?(\D{0,14}?(?:от|за)\s+)?"
    r"(\d[\d  ]{2,5}\d|\d{4,5})(\s*(?:₽|руб\w*|р\.))(\s*(?:/|в)?\s*мес\w*)?")


def _utp_pay_amount(num: str) -> int:
    return int(re.sub(r"\D", "", num) or 0)


def _utp_pay_ok(m) -> bool:
    """Матч платежа годен для унификации: число 1 000–99 999 И есть контекст кредита/«/мес»."""
    amt = _utp_pay_amount(m.group(3))
    return 1000 <= amt <= 99999 and bool(m.group(1) or m.group(5))


# Полоса унификации %: правим только близкие значения (типо-дрейф 57↔58), а РАЗНЫЕ по сути
# проценты (общая «до 57%» vs «Госпрограммы до -30%») НЕ схлопываем — это разные УТП.
_UTP_PCT_BAND = 5


def utp_canon(lines: list[str]) -> tuple[str | None, str | None]:
    """Канон: ДОМИНИРУЮЩИЙ % скидки/выгоды (самый частый; при равенстве — первый) и платёж
    «от N ₽» (первый) по списку строк."""
    pcts: list[str] = []
    pay = None
    for s in lines:
        s = s or ""
        pcts += [m.group(3) for m in _UTP_PCT_RE.finditer(s)]
        if pay is None:
            for m in _UTP_PAY_RE.finditer(s):
                if _utp_pay_ok(m):
                    pay = m.group(3)
                    break
    pct = None
    if pcts:
        order = []
        for v in pcts:
            if v not in order:
                order.append(v)
        pct = max(order, key=lambda v: pcts.count(v))   # самый частый; first-seen выигрывает ничью
    return pct, pay


def utp_apply(s: str, pct: str | None, pay: str | None) -> str:
    """Приводит % скидки/выгоды и платёж к канону pct/pay.
    Для скидки/выгоды процент в пределах одного комплекта должен быть единым."""
    if not s:
        return s
    if pct:
        def _rpct(m):
            v = m.group(3)
            if v == pct:
                return m.group(0)
            return f"{m.group(1)}{m.group(2)}{pct}{m.group(4)}"
        s = _UTP_PCT_RE.sub(_rpct, s)
    if pay:
        def _rp(m):
            if not _utp_pay_ok(m) or m.group(3) == pay:
                return m.group(0)
            return f"{m.group(1) or ''}{m.group(2)}{pay}{m.group(4)}{m.group(5) or ''}"
        s = _UTP_PAY_RE.sub(_rp, s)
    return s


def unify_utp_numbers(titles: list, texts: list, title2: str,
                      sitelinks: list) -> tuple[list, list, str, list, bool]:
    """ГАРД единых чисел: один % скидки/выгоды и один платёж кредита на весь набор РК.
    → (titles, texts, title2, sitelinks, changed)."""
    flat = list(titles) + list(texts) + ([title2] if title2 else [])
    for s in sitelinks:
        flat += [s.get("title", ""), s.get("description", "")]
    pct, pay = utp_canon(flat)
    if not (pct or pay):
        return titles, texts, title2, sitelinks, False
    nt = [utp_apply(t, pct, pay) for t in titles]
    nx = [utp_apply(t, pct, pay) for t in texts]
    n2 = utp_apply(title2, pct, pay)
    nsl = [{"title": utp_apply(s.get("title", ""), pct, pay),
            "description": utp_apply(s.get("description", ""), pct, pay)} for s in sitelinks]
    changed = (nt != list(titles)) or (nx != list(texts)) or (n2 != title2) or (nsl != list(sitelinks))
    return nt, nx, n2, nsl, changed


# Хвостовые «висящие» предлоги/союзы в описании промо — срезаем (числа/₽ НЕ трогаем).
_PROMO_TAIL_DANGLERS = {"в", "во", "на", "с", "со", "к", "ко", "от", "о", "об", "до", "по", "за",
                        "из", "у", "для", "при", "и", "а", "но", "или", "же", "бы", "ли", "не",
                        "ни", "то", "что", "как", "уже", "ещё", "еще"}
# Заглавные слова-стартеры НОВОЙ клаузы: если идут внутри описания — это «приклеенный»
# второй обрывок («…авто Распродаём склад», «…модели Быстрый уход»), режем по ним.
# Только ЗАГЛАВНЫЕ — чтобы не задеть бренды (Haval/Хавейл) и осмысленные слова в нижнем регистре.
_RUNON_STARTER_RE = re.compile(
    r"\s+(?:Распрода\w+|Срочно\w*|Быстр\w+|Успей\w*|Тороп\w+|Спеши\w*|Звони\w*|Налетай\w*|"
    r"Ликвидац\w+|Финальн\w+|Только\b|Осталось\b|Последн\w+|Не\s+упуст\w+|Акция\b)")


def _promo_strip_tail(s: str) -> str:
    """Срезает хвостовые предлоги/союзы описания промо («…Haval H6 при» → «…Haval H6»).
    Числа и ₽ НЕ трогает (в отличие от _strip_trailing_danglers)."""
    words = (s or "").split()
    while len(words) > 1 and re.sub(r"[^\wа-яё]", "", words[-1].lower()) in _PROMO_TAIL_DANGLERS:
        words.pop()
    return " ".join(words)


def fix_promo_desc(s: str) -> str:
    """Грамматическая чистка описания промо (это продолжение фразы «Скидка до N% …»):
    1) двойной предлог в начале «на при покупке» → «при покупке» (артефакт модели);
    2) приклеенный второй обрывок с ЗАГЛАВНОЙ («…авто Распродаём склад») → режем хвост;
    3) висящие в конце предлоги/союзы → срезаем (числа/₽ остаются)."""
    s = re.sub(r"\s+", " ", (s or "").strip())
    s = re.sub(r"^на\s+(?=(?:при|для|от|по|за|до|об?|из|у|к|с|со|в|во)\b)", "", s, flags=re.IGNORECASE)
    m = _RUNON_STARTER_RE.search(s)
    if m and m.start() >= 6:
        s = s[:m.start()].rstrip(" ,.;:—–-")
    return _promo_strip_tail(s).strip()


